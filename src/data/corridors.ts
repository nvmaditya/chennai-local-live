export function reverseCorridor(c: Corridor): Corridor {
  return {
    ...c,
    id: `${c.id}-up`,
    name: `${c.dest}–${c.origin} ${c.isAC ? "AC " : ""}${c.lineId === "mrts" ? "MRTS" : "EMU"}`.replace("  ", " "),
    origin: c.dest,
    dest: c.origin,
    seriesDown: c.seriesUp,
    seriesUp: c.seriesDown,
  };
}

export function directionOf(c: Corridor): Direction {
  // DOWN = towards suburbs. City termini: MSB, MASS.
  const city = new Set(["MSB", "MASS"]);
  if (city.has(c.origin) && !city.has(c.dest)) return "DOWN";
  if (!city.has(c.origin) && city.has(c.dest)) return "UP";
  // both suburban (TBM–CGL): DOWN continues toward CGL
  if (c.dest === "CGL" || c.dest === "TRT" || c.dest === "SPE") return "DOWN";
  if (c.origin === "CGL" || c.origin === "TRT" || c.origin === "SPE") return "UP";
  return "DOWN";
}
